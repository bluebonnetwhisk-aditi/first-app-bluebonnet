import type { VercelRequest, VercelResponse } from '@vercel/node';
import { requireKds } from '../_lib/kds.js';

export const config = { api: { bodyParser: { sizeLimit: '8mb' } } };

const GEMINI_MODELS = [
  'gemini-3.8-flash',
  'gemini-3.5-flash',
  'gemini-3-flash-preview',
  'gemini-flash-latest',
  'gemini-2.5-flash',
  'gemini-2.0-flash',
  'gemini-1.5-flash'
];

/**
 * Server-side Gemini proxy. The API key lives ONLY in the GEMINI_API_KEY
 * environment variable and never reaches the browser.
 * Body: { prompt: string, mimeType: string, base64: string }
 * Returns: { text: string }
 */
export default async function handler(req: VercelRequest, res: VercelResponse) {
  if (!requireKds(req, res)) return;
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method Not Allowed' });

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) return res.status(500).json({ error: 'GEMINI_API_KEY is not configured on the server.' });

  const { prompt, mimeType, base64 } = req.body || {};
  if (typeof prompt !== 'string' || typeof base64 !== 'string' || prompt.length > 20000) {
    return res.status(400).json({ error: 'prompt and base64 required' });
  }
  const mime = typeof mimeType === 'string' && mimeType.includes('png') ? 'image/png' : 'image/jpeg';

  let lastError = 'Failed to scan flyer.';
  for (const model of GEMINI_MODELS) {
    try {
      const r = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'x-goog-api-key': apiKey },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }, { inlineData: { mimeType: mime, data: base64 } }] }],
          generationConfig: { responseMimeType: 'application/json', temperature: 0.1 }
        })
      });
      if (!r.ok) {
        const err: any = await r.json().catch(() => ({}));
        const msg = err.error?.message || `HTTP ${r.status} from ${model}`;
        if ([404, 500, 503].includes(r.status) || (r.status === 400 && msg.includes('models/'))) {
          lastError = msg;
          continue;
        }
        return res.status(502).json({ error: `Gemini API Error (${model}): ${msg}` });
      }
      const data: any = await r.json();
      const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
      if (!text) { lastError = 'No text generated by Gemini.'; continue; }
      return res.status(200).json({ text });
    } catch (e: any) {
      lastError = e?.message || lastError;
    }
  }
  return res.status(502).json({ error: lastError });
}
